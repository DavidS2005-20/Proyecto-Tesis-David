CREATE EXTENSION IF NOT EXISTS pg_trgm;

CREATE INDEX IF NOT EXISTS idx_productos_nombre_trgm
ON productos USING GIN (nombre gin_trgm_ops);

--Función para calcular automáticamente el precio de venta (precio / 0.7)
CREATE OR REPLACE FUNCTION calcular_precio_venta()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.precio_venta := ROUND(NEW.precio / 0.7, 2);
    RETURN NEW;
END;
$$;

-- 3. Trigger al insertar o actualizar un producto
DROP TRIGGER IF EXISTS trg_productos_precio_venta ON productos;

CREATE TRIGGER trg_productos_precio_venta
BEFORE INSERT OR UPDATE ON productos
FOR EACH ROW
EXECUTE FUNCTION calcular_precio_venta();

CREATE TABLE IF NOT EXISTS ventas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    total NUMERIC(18, 2) NOT NULL DEFAULT 0 CHECK (total >= 0),
    creada_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS venta_detalles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venta_id BIGINT NOT NULL REFERENCES ventas(id) ON DELETE RESTRICT,
    producto_id INTEGER NOT NULL REFERENCES productos(id) ON DELETE RESTRICT,
    cantidad INTEGER NOT NULL CHECK (cantidad > 0),
    precio_unitario NUMERIC(12, 2) NOT NULL CHECK (precio_unitario >= 0),
    UNIQUE (venta_id, producto_id)
);

CREATE TABLE IF NOT EXISTS inventario_movimientos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id INTEGER NOT NULL REFERENCES productos(id) ON DELETE RESTRICT,
    tipo TEXT NOT NULL CHECK (tipo IN ('ENTRADA', 'SALIDA')),
    cantidad INTEGER NOT NULL CHECK (cantidad > 0),
    stock_anterior INTEGER NOT NULL CHECK (stock_anterior >= 0),
    stock_posterior INTEGER NOT NULL CHECK (stock_posterior >= 0),
    referencia TEXT,
    venta_id BIGINT REFERENCES ventas(id) ON DELETE RESTRICT,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (
        (tipo = 'ENTRADA' AND stock_posterior = stock_anterior + cantidad)
        OR (tipo = 'SALIDA' AND stock_posterior = stock_anterior - cantidad)
    ),
    CHECK (venta_id IS NULL OR tipo = 'SALIDA')
);

CREATE INDEX IF NOT EXISTS idx_movimientos_producto_fecha
ON inventario_movimientos (producto_id, creado_en DESC);

CREATE INDEX IF NOT EXISTS idx_venta_detalles_venta
ON venta_detalles (venta_id);

